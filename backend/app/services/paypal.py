"""
Talking to PayPal's REST API (sandbox or live).

- Log in with PayPal: connect_url() -> PayPal -> finish_connect(code) stores the user's
  PayPal-verified email, name and payer ID. That is the "verified sender".
- Transaction Search: list_transactions() reads a receiver's own PayPal transactions with the
  receiver's own REST app credentials (client ID + secret). This goes through PayPal's
  official Server SDK (paypal-server-sdk), which is generated by APIMatic.
  Log in with PayPal (Identity API) is not in that SDK yet, so it stays on plain HTTPS.
"""

from datetime import datetime, timedelta, timezone
from urllib.parse import urlencode

import base64
import json
import logging

import httpx
import requests
from apimatic_core.exceptions.auth_validation_exception import AuthValidationException
from paypalserversdk.configuration import Environment
from paypalserversdk.exceptions.api_exception import ApiException
from paypalserversdk.exceptions.o_auth_provider_exception import OAuthProviderException
from paypalserversdk.http.auth.o_auth_2 import ClientCredentialsAuthCredentials
from paypalserversdk.paypal_serversdk_client import PaypalServersdkClient

from app.core.config import settings

API = {"sandbox": "https://api-m.sandbox.paypal.com", "live": "https://api-m.paypal.com"}
WEB = {"sandbox": "https://www.sandbox.paypal.com", "live": "https://www.paypal.com"}
log = logging.getLogger(__name__)
# where a Log in with PayPal code can be swapped for a token: the general OAuth address, and the
# older Identity one some login codes only work at
TOKEN_PATHS = ("/v1/oauth2/token", "/v1/identity/openidconnect/tokenservice")
LOGIN_SCOPES = "openid profile email https://uri.paypal.com/services/paypalattributes"


class PayPalError(Exception):
    """A PayPal call failed; the message is safe to show to the user."""


def _api() -> str:
    return API.get(settings.paypal_env, API["sandbox"])


def login_enabled() -> bool:
    return bool(settings.paypal_client_id and settings.paypal_client_secret)


def _client() -> httpx.Client:
    return httpx.Client(timeout=settings.paypal_timeout_seconds)


def _error_text(r: httpx.Response) -> str:
    try:
        j = r.json()
        return j.get("error_description") or j.get("message") or j.get("error") or r.text[:200]
    except ValueError:
        return r.text[:200] or f"HTTP {r.status_code}"


# ---------------------------------------------------------------- Log in with PayPal
def connect_url(state: str) -> str:
    q = urlencode({"flowEntry": "static", "client_id": settings.paypal_client_id,
                   "response_type": "code", "scope": LOGIN_SCOPES,
                   "redirect_uri": settings.paypal_redirect_uri, "state": state})
    return f"{WEB.get(settings.paypal_env, WEB['sandbox'])}/connect?{q}"


def exchange_code(code: str) -> dict:
    """Authorization code -> the user's PayPal profile (verified by PayPal)."""
    try:
        with _client() as c:
            for path in TOKEN_PATHS:  # a refused code isn't used up, so the second address can be tried
                # OAuth needs the same redirect_uri that was used to start the login
                r = c.post(f"{_api()}{path}",
                           auth=(settings.paypal_client_id, settings.paypal_client_secret),
                           data={"grant_type": "authorization_code", "code": code.strip(),
                                 "redirect_uri": settings.paypal_redirect_uri})
                if r.status_code == 200:
                    break
                log.warning("PayPal login exchange failed at %s: %s %s", path, r.status_code, r.text[:300])
            if r.status_code != 200:
                why = _error_text(r)
                if "not found in cache" in why.lower() or "expired" in why.lower():
                    raise PayPalError("PayPal says this login code was already used or has expired. "
                                      "Click Connect with PayPal again and paste the new link straight away.")
                raise PayPalError(f"PayPal didn't accept the login: {why}")
            info = fetch_profile(c, r.json())
    except httpx.HTTPError as e:
        raise PayPalError(f"Couldn't reach PayPal ({e.__class__.__name__})") from e
    return profile_from(info)


def _jwt_claims(id_token: str | None) -> dict:
    """The claims inside PayPal's id_token (it comes straight from PayPal's token endpoint over HTTPS)."""
    if not id_token or id_token.count(".") != 2:
        return {}
    try:
        part = id_token.split(".")[1]
        return json.loads(base64.urlsafe_b64decode(part + "=" * (-len(part) % 4)))
    except (ValueError, json.JSONDecodeError):
        return {}


def fetch_profile(c: httpx.Client, token_json: dict) -> dict:
    """Read the PayPal profile. Sandbox accounts often fail the detailed format, so fall back to
    the standard OpenID one, then to the identity claims PayPal sent with the token."""
    headers = {"Authorization": f"Bearer {token_json['access_token']}"}
    last = None
    tries = [("/v1/identity/oauth2/userinfo", "paypalv1.1"), ("/v1/identity/oauth2/userinfo", "openid"),
             ("/v1/identity/openidconnect/userinfo", "openid")]  # the last is PayPal's older address
    for path, schema in tries:
        r = c.get(f"{_api()}{path}", params={"schema": schema}, headers=headers)
        if r.status_code == 200:
            info = r.json()
            if info.get("user_id") or info.get("sub"):
                return info
        log.warning("PayPal userinfo %s (%s) failed: %s %s", path, schema, r.status_code, r.text[:300])
        last = r
    claims = _jwt_claims(token_json.get("id_token"))
    if claims.get("sub") or claims.get("user_id"):
        return claims
    raise PayPalError(f"Couldn't read your PayPal profile: {_error_text(last)}")


def profile_from(info: dict) -> dict:
    emails = info.get("emails") or []
    primary = next((e for e in emails if e.get("primary")), emails[0] if emails else {})
    email = (primary.get("value") or info.get("email") or "").strip().lower() or None
    user_id = info.get("user_id") or info.get("sub")
    if not user_id or not email:
        raise PayPalError("PayPal didn't share your account ID and email. In the app's Log in with "
                          "PayPal settings, tick Email and PayPal account ID, save, and try again.")
    verified = info.get("verified_account", info.get("email_verified"))
    return {
        "user_id": user_id,
        "payer_id": info.get("payer_id"),
        "email": email,
        "name": info.get("name") or " ".join(filter(None, [info.get("given_name"), info.get("family_name")])) or None,
        "verified": (str(verified).lower() == "true") if verified is not None else None,
    }


# ---------------------------------------------------------------- Transaction Search (PayPal Server SDK)


def sdk_client(client_id: str, secret: str) -> PaypalServersdkClient:
    """PayPal's official SDK client for one PayPal app. It fetches and refreshes its own token."""
    return PaypalServersdkClient(
        client_credentials_auth_credentials=ClientCredentialsAuthCredentials(
            o_auth_client_id=client_id, o_auth_client_secret=secret),
        environment=Environment.PRODUCTION if settings.paypal_env == "live" else Environment.SANDBOX,
        timeout=settings.paypal_timeout_seconds,
        max_retries=2,  # the SDK retries PayPal's temporary errors (429, 5xx) for us
    )


def _iso(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _sdk_error(e: ApiException) -> PayPalError:
    if isinstance(e, OAuthProviderException):
        why = getattr(e, "error_description", None) or getattr(e, "error", None) or e.reason
        return PayPalError(f"PayPal rejected the client ID / secret: {why}")
    if e.response_code == 403:
        return PayPalError("This PayPal app can't search transactions. In the PayPal "
                           "developer dashboard, turn on Transaction search for the app.")
    why = getattr(e, "message", None) or e.reason
    return PayPalError(f"Transaction search failed: {why}")


def list_transactions(client_id: str, secret: str, start: datetime, end: datetime) -> list[dict]:
    """The account's transactions between start and end (PayPal allows at most 31 days)."""
    if end - start > timedelta(days=31):
        start = end - timedelta(days=31)
    search = sdk_client(client_id, secret).transaction_search
    out: list[dict] = []
    try:
        page = 1
        while page <= 10:
            res = search.search_transactions({
                "start_date": _iso(start), "end_date": _iso(end),
                "fields": "transaction_info,payer_info", "page_size": 100, "page": page})
            j = json.loads(res.text or "{}")  # same JSON shape PayPal documents
            out.extend(j.get("transaction_details") or [])
            if page >= int(j.get("total_pages") or 1):
                break
            page += 1
    except AuthValidationException as e:  # the SDK couldn't get a token with these keys
        raise PayPalError("PayPal rejected the client ID / secret. Copy them again from the "
                          "PayPal developer dashboard (Sandbox, your app).") from e
    except ApiException as e:
        raise _sdk_error(e) from e
    except requests.RequestException as e:
        raise PayPalError(f"Couldn't reach PayPal ({e.__class__.__name__})") from e
    return out


def check_credentials(client_id: str, secret: str) -> None:
    """Raises PayPalError unless the credentials work for Transaction Search."""
    now = datetime.now(timezone.utc)
    list_transactions(client_id, secret, now - timedelta(days=1), now)
