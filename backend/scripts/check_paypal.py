"""
Check the PayPal settings in backend/.env. Run from the backend folder:

    python -m scripts.check_paypal

It tells you whether the keys work (sandbox vs live), whether "Transaction search" and
"Log in with PayPal" are switched on for the app, and shows the latest payments received by
the app's Business sandbox account. Everything goes through PayPal's official Server SDK
(paypal-server-sdk, generated by APIMatic) - the same code Khataz uses.
"""

import sys
from datetime import datetime, timedelta, timezone

import requests
from paypalserversdk.exceptions.api_exception import ApiException

from app.core.config import settings
from app.services import paypal

OK, BAD, WARN = "  [OK]  ", "  [!!]  ", "  [..]  "


def main() -> int:
    print(f"\nPayPal check  (PAYPAL_ENV={settings.paypal_env})\n")
    if not settings.paypal_client_id or not settings.paypal_client_secret:
        print(BAD + "PAYPAL_CLIENT_ID / PAYPAL_CLIENT_SECRET are empty in backend\\.env")
        return 1

    # 1. the keys (the SDK's OAuth call)
    sdk = paypal.sdk_client(settings.paypal_client_id, settings.paypal_client_secret)
    try:
        token = sdk.oauth_2.fetch_token()
    except requests.RequestException as e:
        print(BAD + f"Can't reach PayPal ({e.__class__.__name__}). Check the internet connection.")
        return 1
    except ApiException as e:
        why = getattr(e, "error_description", None) or e.reason
        print(BAD + f"PayPal refused the keys: {why}")
        other = "live" if settings.paypal_env == "sandbox" else "sandbox"
        print("        Make sure they are the " + settings.paypal_env.upper() + " keys (not " + other +
              "), copied without spaces.")
        return 1
    print(OK + "PayPal Server SDK (APIMatic) is installed and talking to PayPal.")
    scopes = getattr(token, "scope", "") or ""
    print(OK + "The keys work (" + settings.paypal_env + ").")

    # 2. which features are on
    if "reporting/search/read" in scopes:
        print(OK + "Transaction search is switched on.")
    else:
        print(WARN + "Transaction search isn't active yet. Switch it on in the app's Features and save;"
              " it can take a few hours to start working.")
    if "openid" in scopes or "identity" in scopes or "paypalattributes" in scopes:
        print(OK + "Log in with PayPal is switched on.")
    else:
        print(WARN + "Couldn't confirm Log in with PayPal from the keys. Check it's switched on in the app's"
              " Features (Return URL: " + settings.paypal_redirect_uri + ").")

    # 3. recent payments to the app's Business account
    now = datetime.now(timezone.utc)
    try:
        rows = paypal.list_transactions(settings.paypal_client_id, settings.paypal_client_secret,
                                        now - timedelta(days=30), now)
        print(OK + f"Transaction search works: {len(rows)} transaction(s) in the last 30 days.")
        for t in rows[-5:]:
            info, payer = t.get("transaction_info", {}), t.get("payer_info", {})
            amt = info.get("transaction_amount", {})
            print(f"        {info.get('transaction_initiation_date', '')[:10]}  {amt.get('value', '?'):>9} "
                  f"{amt.get('currency_code', '')}  from {payer.get('email_address', '?')}  "
                  f"status {info.get('transaction_status', '?')}  id {info.get('transaction_id', '?')}")
    except paypal.PayPalError as e:
        print(WARN + str(e))

    print("\nNext: restart the backend, then in Khataz go to Profile -> Connect with PayPal"
          " and log in with a sandbox Personal account.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
